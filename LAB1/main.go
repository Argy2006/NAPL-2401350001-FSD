// declare variable of different types and assign them some values
package main

import "fmt"

func main() {
	var agee int
	var pi float64 = 3.14
	var s string = "Hello, Go!"
	var b bool = true
	age := 20
	pi = 5.14
	s = "Hello, Go!"
	b = true
	fmt.Println("Integer:", age)
	fmt.Printf("%d", agee)
	fmt.Println("Float:", pi)
	fmt.Println("String:", s)
	fmt.Println("Boolean:", b)
}
